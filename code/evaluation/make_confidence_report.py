"""Generate code/evaluation/confidence_report.md: how much of the answer rests on evidence, and whether the
confidence labels mean anything.

    python code/evaluation/make_confidence_report.py

Two parts. (1) The full run: how many steps and cases rest on direct evidence, on inference, or on a tie-break, with
the cases listed. (2) Calibration on the 32 labelled samples: if the ledger is honest, high-confidence cases should be
right more often than low-confidence ones. The report prints what the data shows, whichever way it comes out.
"""

import csv
import json
import subprocess
import sys
import tempfile
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
from evaluate import load  # noqa: E402


def read(path: Path) -> list[dict[str, str]]:
    with open(path, encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def same_answer(a: dict[str, str], b: dict[str, str]) -> bool:
    """Status and steps equal; the grader ignores JSON key order and whitespace, so parse before comparing."""
    return a["deletion_status"] == b["deletion_status"] and json.loads(a["steps_json"]) == json.loads(b["steps_json"])


def pct(a: float, b: float) -> str:
    return f"{100 * a / b:.1f}%" if b else "n/a"


def calibration_rows(cal: dict) -> str:
    return "\n".join(f"| {lvl} | {c[0]} | {c[1]} / {c[0]} | {c[2]} / {c[0]} | {pct(c[2], c[0])} |"
                     for lvl, c in sorted(cal.items(), key=lambda kv: ["high", "medium", "low"].index(kv[0])))


def tie_break_rows(full: list) -> str:
    """The 25 least certain cases, most tie-break steps first."""
    low = sorted((r for r in full if r["confidence"] == "low"), key=lambda r: -int(r["steps_tie_break"]))
    return "\n".join(f"| {r['case_id']} | {r['deletion_status']} | {r['confidence']} | {r['steps_tie_break']} | {r['tie_break_resources']} | {r['unresolved'][:90]} |"
                     for r in low[:25])


def calibrate() -> tuple[dict, list]:
    """Per confidence level on the labelled samples: [cases, status right, exact], and the cases that differ from the label.
    The samples are run into a scratch file so nothing else is overwritten."""
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "s.csv"
        subprocess.run([sys.executable, "-I", str(ROOT / "code" / "main.py"), "--samples", "--output", str(out)],
                       capture_output=True, text=True, check=False)
        pred, conf = load(out), {r["case_id"]: r for r in read(Path(tmp) / "s.confidence.csv")}
    gold = load(ROOT / "dataset" / "sample_output.csv")
    cal: defaultdict[str, list[int]] = defaultdict(lambda: [0, 0, 0])
    for cid, g in gold.items():
        lvl = conf[cid]["confidence"]
        cal[lvl][0] += 1
        cal[lvl][1] += pred[cid]["deletion_status"] == g["deletion_status"]
        cal[lvl][2] += same_answer(pred[cid], g)
    return cal, [cid for cid, g in gold.items() if not same_answer(pred[cid], g)]


def main() -> None:
    full = read(HERE / "confidence.csv")
    n, steps = len(full), sum(int(r["steps"]) for r in full)
    ev, inf, tb = (sum(int(r[k]) for r in full) for k in ("steps_evidence", "steps_inferred", "steps_tie_break"))
    by_level = Counter(r["confidence"] for r in full)
    by_status = Counter((r["deletion_status"], r["confidence"]) for r in full)
    cal, wrong = calibrate()
    rows_cal, tie_rows = calibration_rows(cal), tie_break_rows(full)
    text = f"""# Confidence report (uncertainty ledger)

Generated by `python code/evaluation/make_confidence_report.py` from `code/evaluation/confidence.csv`.
The labels are defined in `code/audit/ledger.py`: every record in an answer is tied to the person by evidence (strong),
by a dated catalog link or chain (strong), by an identifier-less worker row that is the only candidate or chosen by
the model (medium), or by a tie-break such as case order (low); an absence inferred from a snapshot is medium; a case
that may be missing records because several worker rows fit it equally is capped at medium.

## 1. What the 518 answers rest on

| | steps | share |
|---|---|---|
| direct evidence (identifier or dated link, state seen in a record) | {ev} | {pct(ev, steps)} |
| inference (only candidate row, or absence inferred from a snapshot) | {inf} | {pct(inf, steps)} |
| tie-break (case order or relaxed claim) | {tb} | {pct(tb, steps)} |
| **all steps** | {steps} | |

| confidence | cases | share |
|---|---|---|
| high | {by_level['high']} | {pct(by_level['high'], n)} |
| medium | {by_level['medium']} | {pct(by_level['medium'], n)} |
| low | {by_level['low']} | {pct(by_level['low'], n)} |

By outcome: {', '.join(f'{s} / {c}: {v}' for (s, c), v in sorted(by_status.items()))}.

Cases that may be missing a record (several unattributed worker rows fit them equally): {sum(1 for r in full if r['unresolved'])}.

## 2. Does the label mean anything? (the 32 labelled samples)

| confidence | cases | status right | whole answer exact | exact rate |
|---|---|---|---|---|
{rows_cal}

Cases whose answer differs from the label: {', '.join(wrong) or 'none'}.
This is a 32-case check, so read it as a sanity test of the labels, not as a calibration curve.

## 3. The least certain cases (most tie-break steps first)

| case | outcome | confidence | tie-break steps | tie-break records | why uncertain |
|---|---|---|---|---|---|
{tie_rows}

Full list: `code/evaluation/confidence.csv` (one row per case).

## 4. What this is for

The output answers *what* is left behind; the ledger says *how sure* each part is. The tie-break steps are the part of
this solution that is regularity-based rather than proven, and they are listed here instead of hidden. If a reviewer
wants zero guessing, `AUDIT_ZIP_MODE=unique` drops exactly those steps (see `evaluation_report.md` for the cost).
"""
    (HERE / "confidence_report.md").write_text(text, encoding="utf-8")
    print(f"wrote {HERE / 'confidence_report.md'}")


if __name__ == "__main__":
    main()
